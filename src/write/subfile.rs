use crate::item::{ItemId, ItemKind, ParsedItem};
use crate::promote::{
    CrossImport, add_pub_super, add_pub_super_to_fields, lift_impl_methods,
    rebase_body_super_for_subfile, rebase_pub_super_in_subfile,
};
use crate::write::uses;
use std::collections::{BTreeMap, BTreeSet, HashSet};
use std::fmt::Write;

/// Render one `<bucket>.rs` body. Items are emitted in original source order
/// so the diff is easy to follow; `use` items are skipped here because they
/// already live in the shared prelude block at the top. Items whose id is
/// in `promote` are rewritten with a `pub(super)` visibility prefix.
/// `imports` carries the explicit `use super::<src>::<name>;` lines this
/// bucket needs so the bare-name references to *promoted* items in other
/// sub-buckets still resolve (since `pub use <bkt>::*;` only re-exports
/// `pub` items, the wildcard chain doesn't reach `pub(super)` items).
#[allow(clippy::too_many_arguments)]
pub fn render_sub_file(
    module: &str,
    ids: &[ItemId],
    by_id: &BTreeMap<ItemId, &ParsedItem>,
    use_prelude: &str,
    promote: &BTreeSet<ItemId>,
    impl_lifts: &BTreeSet<ItemId>,
    field_lifts: &BTreeSet<ItemId>,
    imports: &BTreeSet<CrossImport>,
    local_module_roots: &HashSet<String>,
    include_path_prefix: Option<&str>,
) -> String {
    let mut buf = String::new();
    buf.push_str(
        "// Auto-generated by r2factor. Manual edits will be overwritten on next split.\n\n",
    );
    if !use_prelude.is_empty() {
        buf.push_str(use_prelude);
        buf.push('\n');
    }
    for imp in imports {
        // Carry over any cfg attrs the target item had so the use line
        // doesn't try to resolve a symbol that's cfg'd-out for the
        // current target (E0432 otherwise).
        for cfg in &imp.cfg_attrs {
            let _ = writeln!(buf, "{cfg}");
        }
        match &imp.source_bucket {
            Some(src) => {
                let _ = writeln!(buf, "use super::{src}::{name};", name = imp.name);
            }
            None => {
                let _ = writeln!(buf, "use super::{name};", name = imp.name);
            }
        }
    }
    buf.push('\n');

    let mut sorted_ids: Vec<ItemId> = ids.to_vec();
    sorted_ids.sort_by_key(|id| by_id[id].line_start);
    for id in sorted_ids {
        let it = by_id[&id];
        if matches!(it.kind, ItemKind::Use) {
            continue;
        }
        if matches!(it.kind, ItemKind::Mod) && it.name == module {
            let mut module_body =
                unwrap_inline_module_source(&it.source).unwrap_or_else(|| it.source.clone());
            if let Some(prefix) = include_path_prefix {
                module_body = rebase_include_macro_paths(&module_body, prefix);
            }
            buf.push_str(&module_body);
            buf.push_str("\n\n");
            continue;
        }
        // 1) Preserve the original `pub(super)` horizon before adding any
        //    new splitter-local visibility. This catches nested visibilities
        //    such as inherent impl methods and struct fields, while keeping
        //    newly introduced `pub(super)` lifts scoped to the facade.
        let original_scope_rebased = rebase_pub_super_in_subfile(&it.source);
        let after_vis = if promote.contains(&id) {
            // `add_pub_super` handles both keyword AND fields, so skip the
            // separate field lift below for this branch.
            add_pub_super(&original_scope_rebased)
        } else if impl_lifts.contains(&id) {
            lift_impl_methods(&original_scope_rebased)
        } else {
            original_scope_rebased
        };
        // 2) Field-only lift for structs/unions that already had enough
        //    type-level visibility (so weren't in `promote`) but whose
        //    private fields would now be cross-bucket-invisible.
        let after_fields = if field_lifts.contains(&id) {
            add_pub_super_to_fields(&after_vis)
        } else {
            after_vis
        };
        // 3) Rebase relative `super::` paths in expressions/types/etc.
        //    Sub-files are one module-level deeper than the original, so
        //    `super::foo()` in the body needs to become
        //    `super::super::foo()`. Visibility paths are skipped by the
        //    visitor so the steps above are not double-rewritten.
        let mut final_src = rebase_body_super_for_subfile(&after_fields);
        final_src = uses::rebase_use_roots_in_source(&final_src, local_module_roots);
        final_src = uses::rebase_local_module_paths_in_source(&final_src, local_module_roots);
        if let Some(prefix) = include_path_prefix {
            final_src = rebase_include_macro_paths(&final_src, prefix);
        }
        if matches!(it.kind, ItemKind::Mod) && it.name != module {
            final_src = add_bucket_scope_import_to_inline_module(&final_src);
        }
        buf.push_str(&final_src);
        buf.push_str("\n\n");
    }
    buf
}

fn add_bucket_scope_import_to_inline_module(src: &str) -> String {
    if !is_inline_module_source(src) || src.contains("use super::*;") {
        return src.to_string();
    }
    let Some(open) = src.find('{') else {
        return src.to_string();
    };
    let mut insert = open + 1;
    let after_open = &src[insert..];
    for line in after_open.split_inclusive('\n') {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with("#![") {
            insert += line.len();
            continue;
        }
        break;
    }

    let mut out = String::with_capacity(src.len() + "    use super::*;\n".len() + 1);
    out.push_str(&src[..insert]);
    if insert == open + 1 {
        out.push('\n');
    }
    out.push_str("    use super::*;\n");
    out.push_str(&src[insert..]);
    out
}

fn is_inline_module_source(src: &str) -> bool {
    let Ok(file) = syn::parse_file(src) else {
        return false;
    };
    matches!(
        file.items.as_slice(),
        [syn::Item::Mod(module)] if module.content.is_some()
    )
}

fn unwrap_inline_module_source(src: &str) -> Option<String> {
    let file = syn::parse_file(src).ok()?;
    let [syn::Item::Mod(module)] = file.items.as_slice() else {
        return None;
    };
    module.content.as_ref()?;
    let open = src.find('{')?;
    let close = src.rfind('}')?;
    if open >= close {
        return None;
    }
    Some(src[open + 1..close].trim_matches('\n').to_string())
}

fn rebase_include_macro_paths(src: &str, prefix: &str) -> String {
    let mut out = String::with_capacity(src.len());
    let mut rest = src;
    loop {
        let str_pos = rest.find("include_str!(\"");
        let bytes_pos = rest.find("include_bytes!(\"");
        let Some((pos, marker)) = (match (str_pos, bytes_pos) {
            (Some(a), Some(b)) if a <= b => Some((a, "include_str!(\"")),
            (Some(_), Some(b)) => Some((b, "include_bytes!(\"")),
            (Some(a), None) => Some((a, "include_str!(\"")),
            (None, Some(b)) => Some((b, "include_bytes!(\"")),
            (None, None) => None,
        }) else {
            out.push_str(rest);
            break;
        };
        out.push_str(&rest[..pos]);
        out.push_str(marker);
        let path_start = pos + marker.len();
        let after_marker = &rest[path_start..];
        let Some(path_end) = find_string_literal_end(after_marker) else {
            out.push_str(after_marker);
            break;
        };
        let path = &after_marker[..path_end];
        if path.starts_with('/') {
            out.push_str(path);
        } else {
            out.push_str(prefix);
            out.push_str(path);
        }
        rest = &after_marker[path_end..];
    }
    out
}

fn find_string_literal_end(s: &str) -> Option<usize> {
    let mut escaped = false;
    for (idx, ch) in s.char_indices() {
        if escaped {
            escaped = false;
            continue;
        }
        match ch {
            '\\' => escaped = true,
            '"' => return Some(idx),
            _ => {}
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::item::{ItemVis, ParsedItem};

    #[test]
    fn moved_inline_module_can_see_generated_bucket_scope() {
        let item = ParsedItem {
            id: 0,
            kind: ItemKind::Mod,
            name: "nested".to_string(),
            vis: ItemVis::Private,
            is_cfg_test: false,
            line_start: 1,
            line_end: 6,
            source: r#"mod nested {
    #![allow(dead_code)]

    pub fn call() -> u32 {
        helper()
    }
}"#
            .to_string(),
            refs: Vec::new(),
        };
        let by_id = BTreeMap::from([(item.id, &item)]);

        let rendered = render_sub_file(
            "misc",
            &[item.id],
            &by_id,
            "use super::helper;",
            &BTreeSet::new(),
            &BTreeSet::new(),
            &BTreeSet::new(),
            &BTreeSet::new(),
            &HashSet::new(),
            None,
        );

        let attr_pos = rendered
            .find("#![allow(dead_code)]")
            .expect("inner attr in rendered source");
        let import_pos = rendered
            .find("use super::*;")
            .expect("bucket scope import in rendered source");
        assert!(
            attr_pos < import_pos,
            "bucket scope import should be inserted after inner attrs; got:\n{rendered}"
        );
    }
}
